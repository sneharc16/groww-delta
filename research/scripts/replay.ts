import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { executionIdentity } from "../execution";
import { replayStep } from "../replay";
import { researchPolicy } from "../configs/policies";
import { tracesCsv, tracesJsonl } from "../schemas/export";
import { findReplayScenario } from "../../data/replay/scenarios";
import { contentHash } from "../../src/domain/policy/hash";
import { scenarioIdentity } from "../../data/replay/versioning";
import { BUILD_INFO } from "../../src/lib/build-info";
const args=process.argv.slice(2);
const value=(key:string,fallback:string)=>{const index=args.indexOf(key);return index<0?fallback:args[index+1]??fallback;};
const scenarioId=value("--scenario","groww-delta-default"), policy=researchPolicy(value("--policy","full"));
const scenario=findReplayScenario(scenarioId);
if(!scenario)throw new Error("Unknown scenario.");
const ackAt=Number(value("--ack-at","2"));
if(!Number.isInteger(ackAt)||ackAt< -1||ackAt>=scenario.steps.length)throw new Error("Invalid acknowledgement step.");
const traces=scenario.steps.flatMap(step=>replayStep(scenarioId,step.step,ackAt>=0&&step.step>ackAt?ackAt:0,policy).map(item=>item.decisionTrace));
const directory=resolve(value("--output","research/exports/latest"));
await mkdir(directory,{recursive:true});
await writeFile(resolve(directory,"decisions.jsonl"),tracesJsonl(traces));
await writeFile(resolve(directory,"decisions.csv"),tracesCsv(traces));
const metadata={...BUILD_INFO,...executionIdentity(),...scenarioIdentity(scenario),executionTimestamp:new Date().toISOString(),seed:0,scenarioId,policyVersion:policy.version,policyConfigHash:contentHash(policy),startingState:"canonical-initial",acknowledgeAt:ackAt,traceHash:contentHash(traces),traceCount:traces.length};
await writeFile(resolve(directory,"run.json"),JSON.stringify(metadata,null,2)+"\n");
console.log(JSON.stringify({...metadata,output:directory},null,2));
